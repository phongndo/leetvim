std::string python_builtins() {
    std::string out = "# Generated by leetvim: what LeetCode imports in every Python3 solution.\n";
    for (const auto& [module, names] : python_modules) {
        if (names.empty()) {
            out += std::format("import {0} as {0}\n", module);
            continue;
        }
        // A stub re-exports only `x as x` imports.
        out += std::format("from {} import (\n", module);
        for (const auto name : str::split(names, ' ')) {
            if (!name.empty()) out += std::format("    {0} as {0},\n", name);
        }
        out += ")\n";
    }
    return out;
}

std::string ruff_config() {
    std::string out =
        "# Generated by leetvim, which rewrites it; delete this line to keep your changes.\n"
        "# The names LeetCode imports in every Python3 solution, as in __builtins__.pyi.\n"
        "extend-exclude = [\"__builtins__.pyi\"]\n"
        "builtins = [\n";
    for (const auto& [module, names] : python_modules) {
        if (names.empty()) out += std::format("    \"{}\",\n", module);
        for (const auto name : str::split(names, ' ')) {
            if (!name.empty()) out += std::format("    \"{}\",\n", name);
        }
    }
    return out + "]\n";
}


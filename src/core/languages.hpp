#pragma once

#include <span>
#include <string>
#include <string_view>

namespace lv::core {

/// A config file of the user's that takes precedence over a support file: `path` holding
/// `section` (anything, when empty).
struct Precedence {
    std::string_view path;
    std::string_view section;
};

/// A file leetvim keeps in the workspace so a language's LSP knows what LeetCode provides,
/// like clangd's .clangd. Its first line carries generated_marker.
struct SupportFile {
    std::string_view path; // relative to the language's directory in the workspace
    std::string (*content)();
    std::span<const Precedence> unless; // not written while one of these exists
};

/// The first line's marker of a file leetvim generated and may rewrite.
constexpr std::string_view generated_marker = "Generated by leetvim";

struct Language {
    std::string_view slug;    // LeetCode's langSlug: "cpp", "python3", ...
    std::string_view name;    // "C++"
    std::string_view ext;     // file extension without the dot
    std::string_view comment; // line comment prefix
    std::string_view opening; // a file's required first line ("<?php"), before the header
    /// What LeetCode provides implicitly that a solution file itself must hold for an LSP
    /// to see it, like Java's imports or Go's package clause.
    std::string_view prelude;
    /// What LeetCode provides that the workspace can give the LSP instead, like the
    /// standard headers and `using namespace std;` for clangd.
    std::span<const SupportFile> support;
};

std::span<const Language> languages();
/// Looks up a language by slug or common alias ("c++", "py", "go", "rs", "ts", ...).
const Language* find_language(std::string_view slug_or_alias);
/// The preferred language for a file extension ("py" -> python3, "sql" -> mysql).
const Language* language_for_extension(std::string_view ext);

} // namespace lv::core
